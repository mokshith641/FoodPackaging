O2_LIMIT = {1: 5000, 2: 2000, 3: 1000}          # allowed O2 uptake, cc per kg product (assumption)
FM = {0.1: 0.0, 0.25: 0.15, 0.5: 0.35, 1.0: 0.6, 2.0: 0.85}   # thickness position by pack mass
PRODUCE_MATS = ["M01","M02","M03","M04","M13","M14","M17","M18"]

def psat(T):
    return 6.1094*math.exp(17.625*T/(T+243.04)) if T >= 0 else 6.1121*math.exp(22.587*T/(T+273.86))
def fO2(T): return math.exp(40000/8.314*(1/296.15 - 1/(T+273.15)))
def fW(T):  return math.exp(30000/8.314*(1/311.15 - 1/(T+273.15)))
def r5(x):  return int(math.ceil(x/5.0)*5)
def area(m): return 0.15*m**0.67

def kinetic_days(c, T):
    f = c["shelf_life_Q10"] ** ((c["optimal_temp_C"] - T)/10)
    if T < c["optimal_temp_C"]: f = min(f, 1.5)
    return c["base_shelf_life_days"]*f

def pack_cost(mat, t, A, m):
    kg = A*t*1e-6*mat["density_g_cc"]*1000
    return kg*mat["cost_inr_per_kg"]/m, kg*mat["co2e_kg_per_kg"]/m

def np_candidates(c, T, RH, D, m, A, g, use_map):
    aw, ms, lim, s = c["water_activity"], c["moisture_sensitivity_0to3"], c["moisture_limit_pct"], c["o2_sensitivity_0to3"]
    reqW = allowed_g = ratio = None
    if ms > 0 and lim > 0:
        allowed_g = m*1000*lim/100
        dp = (max(RH/100 - aw, 0.15) if aw < 0.9 else max(aw - RH/100, 0.03))*psat(T)
        ratio = dp/(0.90*psat(38))*fW(T)
        reqW = allowed_g/(A*D)/ratio
    reqO = allowed_cc = None
    if s > 0:
        allowed_cc = m*O2_LIMIT[s]
        reqO = allowed_cc/(A*D)/fO2(T)
    if use_map:
        reqO = min(reqO, g["max_pack_OTR_cc_m2_day"]) if reqO else g["max_pack_OTR_cc_m2_day"]
    out = []
    for mat in MATS:
        if mat["standalone_pack_ok"] != "Y" or mat["breathable"] == "Y": continue
        if T <= -5 and mat["low_temp_ok"] == "N": continue
        if mat["thickness_scalable"] == "Y":
            need = max(mat["O2_permeability_cc_um_m2_day"]/reqO if reqO else 0,
                       mat["WV_permeability_g_um_m2_day"]/reqW if reqW else 0)
            tmech = mat["thickness_min_um"] + FM[m]*(mat["thickness_max_um"]-mat["thickness_min_um"])
            t = r5(max(need, tmech))
            if t > mat["thickness_max_um"]: continue
            otr = mat["O2_permeability_cc_um_m2_day"]/t; wv = mat["WV_permeability_g_um_m2_day"]/t
        else:
            t = mat["ref_thickness_um"]; otr = mat["OTR_cc_m2_day_at_ref"]; wv = mat["WVTR_g_m2_day_at_ref"]
            if (reqO and otr > reqO) or (reqW and wv > reqW): continue
        cost, co2 = pack_cost(mat, t, A, m)
        kin = kinetic_days(c, T)
        ext = g["shelf_life_extension_factor"] if use_map else 1.0
        dw = allowed_g/(A*wv*ratio) if reqW else 1e9
        do = allowed_cc/(A*otr*fO2(T)) if reqO and s > 0 else 1e9
        pred = min(kin*ext, dw, do*ext)
        pen = 0.25 if (c["light_sensitive"] == 1 and mat["light_barrier"] == "N") else 0.0
        out.append(dict(mat=mat, t=t, otr=otr, wv=wv, cost=cost, co2=co2, eco=mat["sustainability_score"],
                        pred=pred, pen=pen, yo2="", yco2=""))
    return out, reqO, reqW

def produce_candidates(c, T, m, A):
    R = c["resp_rate_mgCO2_kg_h_at_Topt"]*c["resp_Q10"]**((T-c["optimal_temp_C"])/10)
    RRd = R*0.509*24                               # mL gas / kg / day (RQ ~ 1)
    AW = A/m
    o2lo, o2hi, co2hi = c["optimal_O2_pct_min"], c["optimal_O2_pct_max"], c["optimal_CO2_pct_max"]
    ytgt = (o2lo+o2hi)/200
    reqO = RRd/(AW*(0.21-ytgt))/fO2(T)             # OTR needed at 23C basis
    out = []
    for mid in PRODUCE_MATS:
        mat = MB[mid]; beta = mat["CO2_to_O2_perm_ratio"]
        if mat["thickness_scalable"] == "Y":
            P = mat["O2_permeability_cc_um_m2_day"]
            t = min(max(r5(P/reqO), mat["thickness_min_um"]), mat["thickness_max_um"])
            otr = P/t; wv = mat["WV_permeability_g_um_m2_day"]/t
        else:
            t = mat["ref_thickness_um"]
            otr = min(max(reqO, mat["tunable_OTR_min"]), mat["tunable_OTR_max"]); wv = mat["WVTR_g_m2_day_at_ref"]
        eff = otr*fO2(T)*AW
        yo = max(0.0, 0.21 - RRd/eff); yc = min(RRd/(beta*eff), 1-yo)
        ok = (o2lo-0.5 <= yo*100 <= o2hi+3) and (yc*100 <= co2hi+2)
        if not ok: continue
        inside = (o2lo <= yo*100 <= o2hi) and (yc*100 <= co2hi)
        cost, co2 = pack_cost(mat, t, A, m)
        kin = kinetic_days(c, T)
        pred = kin*(2.0 if inside else 1.5)
        out.append(dict(mat=mat, t=t, otr=otr, wv=wv, cost=cost, co2=co2, eco=mat["sustainability_score"],
                        pred=pred, pen=0.0, yo2=yo*100, yco2=yc*100))
    return out, reqO, R

def choose(cands):
    if not cands: return None, None
    costs = [x["cost"] for x in cands]; lo, hi = min(costs), max(costs)
    for x in cands:
        cn = (x["cost"]-lo)/(hi-lo) if hi > lo else 0.0
        x["s_main"] = 0.6*(1-cn) + 0.4*x["eco"]/100 - x["pen"]
        x["s_eco"]  = 0.3*(1-cn) + 0.7*x["eco"]/100 - x["pen"]
    p = max(cands, key=lambda x: x["s_main"])
    rest = [x for x in cands if x is not p and x["eco"] > p["eco"]]
    a = max(rest, key=lambda x: x["s_eco"]) if rest else None
    return p, a


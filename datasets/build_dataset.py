def M(mid,name,struct,cls,ref,tmin,tmax,scal,otr,wvtr,beta,dens,tens,seal,sealab,stand,transp,light,lowT,
      breath,recyc,bio,cost,co2,tun=("",""),notes=""):
    d = dict(material_id=mid,material=name,structure=struct,material_class=cls,ref_thickness_um=ref,
      thickness_min_um=tmin,thickness_max_um=tmax,thickness_scalable=scal,OTR_cc_m2_day_at_ref=otr,
      WVTR_g_m2_day_at_ref=wvtr,CO2_to_O2_perm_ratio=beta,tunable_OTR_min=tun[0],tunable_OTR_max=tun[1],
      density_g_cc=dens,tensile_MPa=tens,heat_seal_temp_C=seal,sealability=sealab,standalone_pack_ok=stand,
      transparency=transp,light_barrier=light,low_temp_ok=lowT,breathable=breath,recyclability=recyc,
      biodegradable=bio,cost_inr_per_kg=cost,co2e_kg_per_kg=co2,notes=notes)
    if scal == "Y":
        d["O2_permeability_cc_um_m2_day"] = round(otr * ref); d["WV_permeability_g_um_m2_day"] = round(wvtr * ref)
    else:
        d["O2_permeability_cc_um_m2_day"] = ""; d["WV_permeability_g_um_m2_day"] = ""
    d["gas_barrier_class"] = "high" if otr <= 10 else "medium" if otr <= 200 else "low"
    pts = {"recyclable":45,"compostable":35,"limited":15,"non_recyclable":0}[recyc]
    d["sustainability_score"] = round(pts + 40*max(0, 1 - co2/9) + (15 if bio == "Y" else 0))
    return d


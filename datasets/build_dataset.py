COM_KEYS = ["commodity_id","commodity","category","moisture_pct","fat_pct","pH","water_activity",
 "respiring","resp_rate_mgCO2_kg_h_at_Topt","resp_Q10","resp_class_at_5C","ethylene_sensitive",
 "optimal_temp_C","optimal_RH_pct","optimal_O2_pct_min","optimal_O2_pct_max","optimal_CO2_pct_min",
 "optimal_CO2_pct_max","base_shelf_life_days","shelf_life_Q10","o2_sensitivity_0to3",
 "moisture_sensitivity_0to3","light_sensitive","moisture_limit_pct","default_storage_type",
 "data_confidence","notes"]

def NP(cid,name,cat,moist,fat,ph,aw,Topt,RH,base,q10,o2s,ms,light,mlim,stor="ambient",conf="medium",notes=""):
    return dict(commodity_id=cid,commodity=name,category=cat,moisture_pct=moist,fat_pct=fat,pH=ph,
        water_activity=aw,respiring="N",resp_rate_mgCO2_kg_h_at_Topt="",resp_Q10="",resp_class_at_5C="",
        ethylene_sensitive="N",optimal_temp_C=Topt,optimal_RH_pct=RH,optimal_O2_pct_min="",optimal_O2_pct_max="",
        optimal_CO2_pct_min="",optimal_CO2_pct_max="",base_shelf_life_days=base,shelf_life_Q10=q10,
        o2_sensitivity_0to3=o2s,moisture_sensitivity_0to3=ms,light_sensitive=light,moisture_limit_pct=mlim,
        default_storage_type=stor,data_confidence=conf,notes=notes)

def PR(cid,name,cat,moist,fat,ph,aw,resp,q10r,eth,Topt,RH,o2lo,o2hi,co2lo,co2hi,base,q10sl,mlim,light,conf="medium",notes=""):
    d = NP(cid,name,cat,moist,fat,ph,aw,Topt,RH,base,q10sl,0,2,light,mlim,
           "chilled" if Topt <= 5 else "cool",conf,notes)
    d.update(respiring="Y",resp_rate_mgCO2_kg_h_at_Topt=resp,resp_Q10=q10r,ethylene_sensitive=eth,
             optimal_O2_pct_min=o2lo,optimal_O2_pct_max=o2hi,optimal_CO2_pct_min=co2lo,optimal_CO2_pct_max=co2hi)
    r5 = resp * q10r ** ((5 - Topt) / 10)
    d["resp_class_at_5C"] = ("very_low" if r5<5 else "low" if r5<10 else "moderate" if r5<20 else
                             "high" if r5<40 else "very_high" if r5<60 else "extremely_high")
    return d

